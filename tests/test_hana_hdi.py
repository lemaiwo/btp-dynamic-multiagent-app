class DriverError(Exception):
    """Like ``hdbcli.dbapi.Error``: a code and a text that names the host."""

    def __init__(self, errorcode: int, text: str) -> None:
        super().__init__(errorcode, text)
        self.errorcode = errorcode


LEAKY = f"connect failed {{hana.example.internal:443}} user CONTAINER_1_DT pwd {PASSWORD}"


def _no_leak(error: BaseException) -> None:
    shown = str(error) + repr(error)
    for secret in (PASSWORD, "MIIFAKE", "hana.example.internal", "CONTAINER_1_DT"):
        assert secret not in shown
    # Not chained either: a logged traceback would print the driver's text.
    assert error.__cause__ is None and error.__suppress_context__


