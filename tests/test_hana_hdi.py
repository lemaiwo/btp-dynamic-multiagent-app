def test_a_container_of_a_newer_generation_is_not_touched_at_all():
    """An older app version (a rollback, an old instance during a rolling
    deploy) generates fewer artifacts. The container's record says a newer
    generation was MADE and what is deployed is that schema: the older
    version writes, makes and undeploys nothing, and reports what it found."""
    container = FakeContainer(NEWER, generation=GEN + 3)
    before = dict(container.work)

    result = run(container)

    assert (result.changed, result.undeployed, result.newer_generation) == (False, (), GEN + 3)
    assert container.after_setup() == ["LOCK", "LIST", "READ", "LIST_DEPLOYED", "rollback"]
