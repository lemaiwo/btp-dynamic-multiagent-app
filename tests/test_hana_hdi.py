def test_a_table_artifact_holds_exactly_the_columns_the_dialect_would_create():
    """Checked against the dialect's own ``CREATE TABLE``, column by column."""
    for table in Base.metadata.sorted_tables:
        whole = str(CreateTable(table).compile(dialect=HANA))
        expected = set()
        for line in whole.splitlines()[2:-2]:
            line = line.strip().rstrip(",").strip()
            if line.startswith(("CONSTRAINT ", "FOREIGN KEY", "UNIQUE ")):
                continue
            expected.add(line.replace(" DATETIME", " TIMESTAMP"))
        content = FILES[f"src/{table.name}.hdbtable"]
        got = {line.strip().rstrip(",") for line in content.splitlines()[1:-1]}
        assert got == expected, table.name
        assert len(got) == len(table.columns) + 1  # and the primary key


