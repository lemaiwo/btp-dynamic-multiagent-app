@pytest.mark.parametrize("procedure", ["LOCK", "READ", "LIST_DEPLOYED", "WRITE", "DELETE", "MAKE"])
def test_an_error_row_is_the_failure_and_the_next_deploy_still_works(procedure):
    """The procedure itself does not raise; its message table says so. One
    attempt: a refused artifact is refused again however often. Nothing
    deployed changed; whatever the file system looks like now, the next
    deploy brings the container to the generated files."""
