class _Driver:
    """``hdbcli.dbapi.connect``: what it was given, and a connection that
    starts, as the real one does, with autocommit ON."""

    def __init__(self) -> None:
        self.kwargs: dict[str, Any] = {}
        self.autocommit = True

    def connect(self, **kwargs: Any) -> _Driver:
        self.kwargs = kwargs
        return self

    def setautocommit(self, value: bool) -> None:
        self.autocommit = value


def test_the_real_connection_is_encrypted_validated_and_one_transaction(monkeypatch):
    import hdbcli.dbapi

    driver = _Driver()
    monkeypatch.setattr(hdbcli.dbapi, "connect", driver.connect)
    connection = hana_hdi._connect(CREDENTIALS)
    assert driver.kwargs == {
        "address": "hana.example.internal", "port": 443, "user": "CONTAINER_1_DT",
        "password": PASSWORD, "encrypt": True, "sslValidateCertificate": True,
        "sslTrustStore": CERTIFICATE,
    }
    # hdbcli's default is autocommit: every HDI call would commit alone.
    assert connection is driver and driver.autocommit is False

    driver = _Driver()
    monkeypatch.setattr(hdbcli.dbapi, "connect", driver.connect)
    hana_hdi._connect(HdiCredentials("h", 443, "C1", "u", PASSWORD))
    assert driver.kwargs["encrypt"] is True and driver.kwargs["sslValidateCertificate"] is True
    assert "sslTrustStore" not in driver.kwargs and driver.autocommit is False


