def test_an_empty_container_gets_every_artifact_in_one_transaction():
    container = FakeContainer()
    result = run(container)

    assert result.changed and result.undeployed == () and result.newer_generation is None
    assert result.deployed == tuple(FILES)
    # The record is looked for, not found, and written with the files.
    assert container.after_setup() == [
        "LOCK", "LIST", "LIST_DEPLOYED", "LIST", "WRITE", "MAKE", "WRITE", "commit"]
    assert container.connections[0].locked is False
    assert container.made == [(list(FILES), [])]
    assert container.deployed == FILES
    assert (container.generation, container.is_made) == (GEN, True)
    assert container.record_matches_schema()
    assert json.loads(container.work[RECORD])["digest"] == hana_hdi.load_history()[GEN]
    assert container.connections[0].closed == 1


def test_the_lock_wait_fits_inside_a_default_start_timeout():
    """Cloud Foundry kills an app that has not started within 60 s (the
    default): an instance waiting for the lock must give up, or get it and
    finish, well before that. A first full deploy was measured at 3 s."""
    assert 10_000 <= hana_hdi.LOCK_WAIT_MS <= 30_000


def test_the_lock_is_taken_first_and_no_ddl_follows_it():
    """Creating a temporary table is DDL, and DDL commits: after the lock it
    would release the lock and commit half a deployment."""
    container = FakeContainer()
    run(container)
    statements = container.connections[0].statements
    lock = next(i for i, s in enumerate(statements) if ".LOCK(" in s)
    assert all(s.startswith("CREATE LOCAL TEMPORARY") for s in statements[:lock])
    assert len(statements[:lock]) == len(hana_hdi._TEMP_TABLES)
    assert not [s for s in statements[lock:] if s.startswith("CREATE ")]
    assert container.calls[0] == "commit" and container.calls[1] == "LOCK"


def test_a_container_that_already_holds_the_files_is_left_alone():
    """Idempotent, and cheap: four reads under the lock, no write, no make."""
    container = FakeContainer(FILES, generation=GEN)
    for _ in range(2):
        result = run(container)
        assert not result.changed and result.undeployed == ()
        assert result.deployed == tuple(FILES) and result.newer_generation is None
    assert container.after_setup() == [
        "LOCK", "LIST", "READ", "LIST_DEPLOYED", "LIST", "commit"]
    assert container.made == [] and container.generation == GEN


def test_files_a_failed_deploy_left_behind_are_removed_even_when_nothing_is_made():
    leftover = "src/zz_broken.hdbindex"
    container = FakeContainer(FILES, generation=GEN)
    container.work[leftover] = "INDEX nonsense"
