def test_a_failed_make_after_a_delete_leaves_a_container_the_next_deploy_can_use():
    """HDI has committed the DELETE of the stale file when the make fails,
    and no rollback brings it back: the file is gone from the file system
    and still deployed. The next deploy must not try to delete it again
    (HDI answers "could not be found", and every later start failed on
    that) and must still undeploy it."""
    stale = "src/old.hdbindex"
