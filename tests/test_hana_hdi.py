def _small(*extra: Any) -> MetaData:
    metadata = MetaData()
    Table("parents", metadata, Column("id", Integer, primary_key=True))
    Table(
        "children", metadata,
        Column("id", String(36), primary_key=True),
        Column("parent_id", Integer, ForeignKey("parents.id"), nullable=False),
        Column("label", String(20)),
        Column("body", Text),
        Column("seen_at", DateTime(timezone=True)),
        *extra,
    )
    return metadata


def test_an_index_that_leaves_the_models_leaves_the_artifacts():
    with_index = artifacts(_small(Index("ix_children_label", "label")))
    without = artifacts(_small())
    assert set(with_index) - set(without) == {"src/ix_children_label.hdbindex"}
    assert with_index["src/ix_children_label.hdbindex"] == (
        "INDEX ix_children_label ON children (label)\n"
    )
    # An unnamed foreign key gets a stable name; no cascade was asked for.
    assert without["src/fk_children_parent_id.hdbconstraint"] == (
        "CONSTRAINT fk_children_parent_id ON children FOREIGN KEY (parent_id) "
        "REFERENCES parents (id)\n"
    )
    assert "seen_at TIMESTAMP" in without["src/children.hdbtable"]


