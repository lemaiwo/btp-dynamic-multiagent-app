@pytest.mark.parametrize("held, made, app", [
    (None, True, GEN),      # deployed before records existed
    (GEN, False, GEN),      # the make finished, its "made" record did not
    (GEN, True, GEN + 1),   # the next generation changed no file
    (GEN, False, GEN + 1),
])
def test_the_same_files_without_a_current_record_only_get_the_record(held, made, app):
    """Nothing to make; the record is brought to "this generation, made"."""
    container = FakeContainer(FILES, generation=held, made=made)
    result = run(container, generation=app)
    assert not result.changed
    assert "MAKE" not in container.calls and "DELETE" not in container.calls
    assert container.calls[-2:] == ["WRITE", "commit"]
    assert (container.generation, container.is_made) == (app, True)
    assert container.deployed == FILES and container.record_matches_schema()


