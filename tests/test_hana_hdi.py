def test_an_artifact_that_is_no_longer_generated_is_undeployed():
    gone = "src/ix_job_runs_removed.hdbindex"
    container = FakeContainer(
        {**FILES, gone: "INDEX ix_job_runs_removed ON job_runs (id)\n"}, generation=GEN)

    result = run(container, generation=GEN + 1)

    assert result.changed and result.undeployed == (gone,)
    # Out of the file system first, then named to the make as "undeploy".
    assert container.after_setup() == [
        "LOCK", "LIST", "READ", "LIST_DEPLOYED", "LIST", "WRITE", "DELETE", "MAKE", "WRITE",
        "commit"]
    assert container.deleted == [[gone]]
    assert container.made == [(list(FILES), [gone])]
    assert container.deployed == FILES and gone not in container.work
    # And the next start finds nothing to do.
    assert not run(container, generation=GEN + 1).changed


def test_delete_acts_on_the_file_system_and_undeploy_on_what_is_deployed():
    """The two can differ. A stale file that is deployed but no longer in the
    file system must not be deleted (HDI answers "could not be found") yet
    must be undeployed; a leftover file that was never deployed is deleted
    and is nothing to undeploy."""
    stale = "src/ix_stale.hdbindex"
    leftover = "src/zz_leftover.hdbindex"
    container = FakeContainer({**FILES, stale: "INDEX ix_stale ON job_runs (id)\n"})
    del container.work[stale]
    container.work[leftover] = "INDEX zz_leftover ON job_runs (id)\n"

    result = run(container)

    assert result.changed and result.undeployed == (stale,)
    assert container.deleted == [[leftover]]
    assert container.made == [(list(FILES), [stale])]
    assert container.deployed == FILES
    assert {p for p in container.work if p.startswith("src/")} == set(FILES)


def test_a_stale_file_missing_from_the_file_system_needs_no_delete_call():
    stale = "src/ix_stale.hdbindex"
    container = FakeContainer({**FILES, stale: "INDEX ix_stale ON job_runs (id)\n"})
    del container.work[stale]
    assert run(container).undeployed == (stale,)
    assert "DELETE" not in container.calls


