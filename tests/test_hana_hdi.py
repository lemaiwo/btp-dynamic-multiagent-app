MESSAGE_COLUMNS = ("REQUEST_ID", "ROW_ID", "LEVEL", "TYPE", "LIBRARY_ID", "PLUGIN_ID",
                   "PATH", "SEVERITY", "MESSAGE_CODE", "MESSAGE", "LOCATION",
                   "LOCATION_PATH", "TIMESTAMP_UTC")
LISTING_COLUMNS = ("PATH", "CREATE_USER_NAME", "CREATE_APPUSER_NAME", "CREATE_TIMESTAMP_UTC",
                   "MODIFICATION_USER_NAME", "MODIFICATION_APPUSER_NAME",
                   "MODIFICATION_TIMESTAMP_UTC", "SIZE", "SHA256")
GEN = hana_hdi.HANA_SCHEMA_GENERATION
RECORD = hana_hdi.GENERATION_FILE


def message(severity: str, text: str, path: str | None = None, code: int = 0) -> tuple:
    return (1, 1, 0, "HDI", None, None, path, severity, code, text, None, None, None)


def not_found(path: str) -> list[tuple]:
    """HDI's answer to a LIST of a path that does not exist, with the
    message codes read off a real container."""
    return [
        message("ERROR", f'The file "{path}" could not be found', code=8212757),
        message("ERROR", "Could not read work files", code=8211562),
        message("ERROR", "Some requested files/folders could not be found", code=8212764),
        message("ERROR", 'Reading 1 work files from the container "CONTAINER_1"... failed',
                code=8214188),
    ]


def folder_not_found(path: str, procedure: str = "LIST") -> list[tuple]:
    """HDI's answer to a LIST / LIST_DEPLOYED of a folder that does not
    exist: what a container nobody deployed to says about ``src/``. Message
    codes read off a real, never-used container; the two procedures differ
    in two of the four."""
    kind, read, summary = (
        ("active", 8211563, 8214191) if procedure == "LIST_DEPLOYED"
        else ("work", 8211562, 8214188)
    )
    return [
        message("ERROR", f'The folder "{path}" could not be found', code=8212760),
        message("ERROR", f"Could not read {kind} files", code=read),
        message("ERROR", "Some requested files/folders could not be found", code=8212764),
        message("ERROR", f'Reading 1 {kind} files from the container "CONTAINER_1"... failed',
                code=summary),
    ]


def record(generation: int, files: dict[str, str] = FILES, *, made: bool = True) -> dict:
    return {RECORD: json.dumps({
        "generation": generation, "made": made, "digest": hana_hdi.schema_digest(files)})}


class FakeContainer:
    """An HDI container as the deployment sees it: the deployed files, the
    design-time file system (``work``; it also holds the generation record),
    and procedures that answer with message tables the way the real ones do
    (a DELETE or LIST of a path that is not there is an ERROR row). As
    measured on a real container, every procedure commits its own work: a
    WRITE, a DELETE and a successful MAKE stay whatever the client's
    transaction does afterwards; a refused MAKE changes nothing deployed.
    ``commit`` / ``rollback`` only end the lock. ``calls`` is the order of
    everything."""

    def __init__(self, deployed: dict[str, str] | None = None,
                 generation: int | None = None, *, made: bool = True) -> None:
        self.deployed = dict(deployed or {})
        self.work = dict(self.deployed)
        if generation is not None:
            self.work.update(record(generation, self.deployed, made=made))
        self.replies: dict[str, list[tuple]] = {}
        self.fail_on: dict[str, Exception] = {}
        self.calls: list[str] = []
        self.made: list[tuple[list[str], list[str]]] = []
        self.deleted: list[list[str]] = []
        self.connections: list[FakeConnection] = []

    def connect(self, credentials: HdiCredentials) -> FakeConnection:
        connection = FakeConnection(self)
        self.connections.append(connection)
        return connection

    @property
    def generation(self) -> int | None:
        raw = self.work.get(RECORD)
        return None if raw is None else json.loads(raw)["generation"]

    @property
    def is_made(self) -> bool | None:
        raw = self.work.get(RECORD)
        return None if raw is None else json.loads(raw)["made"]

    def record_matches_schema(self) -> bool:
        return json.loads(self.work[RECORD])["digest"] == hana_hdi.schema_digest(self.deployed)

    def after_setup(self) -> list[str]:
        """The calls of the last deployment, after its temporary tables
        were committed (every deployment starts ``commit``, ``LOCK``)."""
        starts = [i for i, call in enumerate(self.calls[:-1])
                  if call == "commit" and self.calls[i + 1] == "LOCK"]
        return self.calls[starts[-1] + 1:]


class FakeConnection:
    def __init__(self, container: FakeContainer) -> None:
        self.container = container
        self.temp: dict[str, list[tuple]] = {}
        self.closed = 0
        self.locked = False
        self.statements: list[str] = []

    def state(self) -> tuple[dict[str, str], dict[str, str]]:
        return self.container.work, self.container.deployed

    def cursor(self) -> FakeCursor:
        return FakeCursor(self)

    def commit(self) -> None:
        self.container.calls.append("commit")
        self.locked = False

    def rollback(self) -> None:
        self.container.calls.append("rollback")
        self.locked = False

    def close(self) -> None:
        self.closed += 1


class FakeCursor:
    def __init__(self, connection: FakeConnection) -> None:
        self.connection = connection
        self._sets: list[tuple[tuple[str, ...], list[tuple]]] = []
        self.description: Any = None

    # -- the DB-API surface the deployment uses --
    def execute(self, statement: str, parameters: Any = None) -> None:
        connection = self.connection
        container = connection.container
        connection.statements.append(statement)
        created = re.fullmatch(
            r"CREATE LOCAL TEMPORARY COLUMN TABLE (#\w+) LIKE _SYS_DI\.(\w+)", statement)
        if created:
            assert created.group(1) not in connection.temp
            assert not connection.locked, "DDL after the lock would release it"
            connection.temp[created.group(1)] = []
            self._answer([])
            return
        called = re.fullmatch(r'CALL "CONTAINER_1#DI"\.(\w+)\(([^)]*)\)', statement)
        assert called, statement
        procedure, arguments = called.group(1), [a.strip() for a in called.group(2).split(",")]
        container.calls.append(procedure)
        if procedure in container.fail_on:
            raise container.fail_on[procedure]
        work, deployed = connection.state()
        messages = list(container.replies.get(procedure, [message("INFO", "ok")]))
        sets: list[tuple[tuple[str, ...], list[tuple]]] = [(MESSAGE_COLUMNS, messages)]
        failed = any(row[7] == "ERROR" for row in messages)

        def listing(files: dict[str, str], paths: list[tuple]) -> list[tuple]:
            rows = []
            for (path,) in paths:
                if path.endswith("/"):
                    found = {p: c for p, c in files.items() if p.startswith(path)}
                    if not found:
                        # A folder exists only through the files below it.
                        messages.extend(folder_not_found(path, procedure))
                        continue
                    rows.append((path, "U", None, None, "U", None, None, 0, None))
                elif path in files:
                    found = {path: files[path]}
                else:
                    messages.extend(not_found(path))
                    found = {}
                rows += [(p, "U", None, None, "U", None, None, len(c),
                          hashlib.sha256(c.encode()).hexdigest().upper())
                         for p, c in sorted(found.items())]
            return rows

        if procedure == "LOCK":
            assert arguments[0] == str(hana_hdi.LOCK_WAIT_MS)
            connection.locked = True
        elif procedure == "LIST_DEPLOYED":
            sets.append((LISTING_COLUMNS, listing(deployed, connection.temp[arguments[0]])))
        elif procedure == "LIST":
            sets.append((LISTING_COLUMNS, listing(work, connection.temp[arguments[0]])))
        elif procedure == "READ":
            rows = listing(work, connection.temp[arguments[0]])
            sets.append((LISTING_COLUMNS + ("CONTENT",),
                         [row + (work[row[0]].encode(),) for row in rows]))
        elif procedure == "WRITE" and not failed:
            for path, content in connection.temp[arguments[0]]:
                if content is not None:
                    work[path] = content.decode("utf-8")
        elif procedure == "DELETE" and not failed:
            paths = [p for (p,) in connection.temp[arguments[0]]]
            container.deleted.append(paths)
            for path in paths:
                if path not in work:
                    messages.append(message("ERROR", f'The file "{path}" could not be found'))
                else:
                    del work[path]
        elif procedure == "MAKE" and not failed:
            deploy = [p for (p,) in connection.temp[arguments[0]]]
            undeploy = [p for (p,) in connection.temp[arguments[1]]]
            assert connection.temp[arguments[2]] == []
            container.made.append((deploy, undeploy))
            for path in deploy:
                deployed[path] = work[path]
            for path in undeploy:
                assert path not in work, "undeployed while still in the file system"
                del deployed[path]
        self._answer(sets)

    def executemany(self, statement: str, rows: list[tuple]) -> None:
        inserted = re.fullmatch(r"INSERT INTO (#\w+) VALUES \(([?, ]+)\)", statement)
        assert inserted, statement
        assert all(len(row) == inserted.group(2).count("?") for row in rows)
        self.connection.temp[inserted.group(1)].extend(rows)

    def fetchall(self) -> list[tuple]:
        return self._sets[0][1]

    def nextset(self) -> bool:
        self._sets.pop(0)
        self.description = [(c,) for c in self._sets[0][0]] if self._sets else None
        return bool(self._sets)

    def _answer(self, sets: list) -> None:
        self._sets = list(sets)
        self.description = [(c,) for c in self._sets[0][0]] if self._sets else None


def run(container: FakeContainer, files: dict[str, str] = FILES, *, generation: int = GEN,
        allow_drop: bool = False) -> hana_hdi.DeployResult:
    return deploy_files(CREDENTIALS, files, generation=generation, allow_drop=allow_drop,
                        connect=container.connect)


