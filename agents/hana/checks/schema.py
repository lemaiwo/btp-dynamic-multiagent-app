"""``builtin:hana`` checks of the category ``schema``.

Each check is data: ``register(Check(...))`` at import, with its SQL as a
constant and every variable part a ``?`` bind (see :mod:`.base`).

Phase 3: checks across one or two schemas; a check that compares two declares
``other_schema`` (same rule as ``schema``, bound as given).

The target is on-premise SAP HANA 2.0 (SPS07); a ``# on-prem:`` comment per
check says how it differs from hana-cli and where it ran. Only catalogue
views of ``SYS`` are read: names and metadata, never a row of a user table,
a ``COMMENTS`` text, a ``DEFINITION`` or a column's ``DEFAULT_VALUE``.
hana-cli diffs and draws in JavaScript; here the diff is SQL (one
``FULL OUTER JOIN`` of the two sides per part) and nothing is drawn.
:data:`CHECKS` holds them in registration order; its test file
(``tests/test_hanadb_checks_schema.py``) pins their names.
"""

from __future__ import annotations

from agents.hana.checks.base import Check, Statement, register

# Optional filter on one table: the CAST gives a NULL bind a type (the form
# of performance.py; the NULL bind is unverified on SPS07).
_NULL_OBJECT = "CAST(? AS NVARCHAR(256)) IS NULL"


def _in_both(column: str, own: str = "?", other: str = "?") -> str:
    """The rows of one side whose table also exists in the other schema."""
    return (f"SCHEMA_NAME = {own} AND {column} IN"
            f" (SELECT TABLE_NAME FROM SYS.TABLES WHERE SCHEMA_NAME = {other})")


# Binds of the parts that compare tables present in both schemas: side A is
# `schema` restricted to tables of `other_schema`, side B the other way round.
_BOTH_BINDS = ("top_plus_one", "schema", "other_schema", "other_schema", "schema")

# on-prem: hana-cli reads SYS.TABLES / TABLE_COLUMNS / INDEX_COLUMNS /
# TRIGGERS of each schema and diffs the lists in JS (the PostgreSQL branch and
# the table filter with wildcards are dropped). Here each part is ONE FULL
# OUTER JOIN of the two schemas' rows: `tables_only_in_one` lists the tables
# of one side only (ONLY_IN says which argument); the other three parts look
# only at tables present in both (a table of one side only would repeat its
# columns, indexes and triggers) and list what is missing on one side or
# differs: data type, length, scale, nullability; an index column's
# position; a trigger's action time and event. Index names generated by the
# system (primary keys) differ between schemas and show up as differences.
# Constraints and views are not compared. Trigger DEFINITION is never read.
# cost: TABLE_COLUMNS of two large schemas (an S/4 schema) is a large join;
# bounded in rows by `top`, not in work.
# on-prem: not yet run
COMPARE_SCHEMA = Check(
    name="compareSchema",
    category="schema",
    purpose=("Tables, columns, index columns and triggers that differ between schema and"
             " other_schema; no views or constraints."),
    source="bin/compareSchema.js",
    statements=(
        Statement(
            "tables_only_in_one",
            "SELECT TOP ? CASE WHEN A.TABLE_NAME IS NULL THEN 'other_schema' ELSE 'schema'"
            " END AS ONLY_IN, COALESCE(A.TABLE_NAME, B.TABLE_NAME) AS TABLE_NAME,"
            " COALESCE(A.TABLE_TYPE, B.TABLE_TYPE) AS TABLE_TYPE"
            " FROM (SELECT TABLE_NAME, TABLE_TYPE FROM SYS.TABLES WHERE SCHEMA_NAME = ?) A"
            " FULL OUTER JOIN"
            " (SELECT TABLE_NAME, TABLE_TYPE FROM SYS.TABLES WHERE SCHEMA_NAME = ?) B"
            " ON A.TABLE_NAME = B.TABLE_NAME"
            " WHERE A.TABLE_NAME IS NULL OR B.TABLE_NAME IS NULL"
            " ORDER BY TABLE_NAME",
            ("top_plus_one", "schema", "other_schema"),
        ),
        Statement(
            "column_differences",
            "SELECT TOP ? CASE WHEN A.COLUMN_NAME IS NULL THEN 'other_schema'"
            " WHEN B.COLUMN_NAME IS NULL THEN 'schema' ELSE 'both' END AS ONLY_IN,"
            " COALESCE(A.TABLE_NAME, B.TABLE_NAME) AS TABLE_NAME,"
            " COALESCE(A.COLUMN_NAME, B.COLUMN_NAME) AS COLUMN_NAME,"
            " A.DATA_TYPE_NAME AS DATA_TYPE_NAME, B.DATA_TYPE_NAME AS OTHER_DATA_TYPE_NAME,"
            " A.LENGTH AS LENGTH, B.LENGTH AS OTHER_LENGTH,"
            " A.SCALE AS SCALE, B.SCALE AS OTHER_SCALE,"
            " A.IS_NULLABLE AS IS_NULLABLE, B.IS_NULLABLE AS OTHER_IS_NULLABLE"
            " FROM (SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE_NAME, LENGTH, SCALE, IS_NULLABLE"
            f" FROM SYS.TABLE_COLUMNS WHERE {_in_both('TABLE_NAME')}) A"
            " FULL OUTER JOIN"
            " (SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE_NAME, LENGTH, SCALE, IS_NULLABLE"
            f" FROM SYS.TABLE_COLUMNS WHERE {_in_both('TABLE_NAME')}) B"
            " ON A.TABLE_NAME = B.TABLE_NAME AND A.COLUMN_NAME = B.COLUMN_NAME"
            " WHERE A.COLUMN_NAME IS NULL OR B.COLUMN_NAME IS NULL"
            " OR A.DATA_TYPE_NAME <> B.DATA_TYPE_NAME"
            " OR COALESCE(A.LENGTH, -1) <> COALESCE(B.LENGTH, -1)"
            " OR COALESCE(A.SCALE, -1) <> COALESCE(B.SCALE, -1)"
            " OR A.IS_NULLABLE <> B.IS_NULLABLE"
            " ORDER BY TABLE_NAME, COLUMN_NAME",
            _BOTH_BINDS,
        ),
        Statement(
            "index_differences",
            "SELECT TOP ? CASE WHEN A.COLUMN_NAME IS NULL THEN 'other_schema'"
            " WHEN B.COLUMN_NAME IS NULL THEN 'schema' ELSE 'both' END AS ONLY_IN,"
            " COALESCE(A.TABLE_NAME, B.TABLE_NAME) AS TABLE_NAME,"
            " COALESCE(A.INDEX_NAME, B.INDEX_NAME) AS INDEX_NAME,"
            " COALESCE(A.COLUMN_NAME, B.COLUMN_NAME) AS COLUMN_NAME,"
            " A.POSITION AS POSITION, B.POSITION AS OTHER_POSITION"
            " FROM (SELECT TABLE_NAME, INDEX_NAME, COLUMN_NAME, POSITION"
            f" FROM SYS.INDEX_COLUMNS WHERE {_in_both('TABLE_NAME')}) A"
            " FULL OUTER JOIN"
            " (SELECT TABLE_NAME, INDEX_NAME, COLUMN_NAME, POSITION"
            f" FROM SYS.INDEX_COLUMNS WHERE {_in_both('TABLE_NAME')}) B"
            " ON A.TABLE_NAME = B.TABLE_NAME AND A.INDEX_NAME = B.INDEX_NAME"
            " AND A.COLUMN_NAME = B.COLUMN_NAME"
            " WHERE A.COLUMN_NAME IS NULL OR B.COLUMN_NAME IS NULL"
            " OR A.POSITION <> B.POSITION"
            " ORDER BY TABLE_NAME, INDEX_NAME, COLUMN_NAME",
            _BOTH_BINDS,
        ),
        Statement(
            "trigger_differences",
            "SELECT TOP ? CASE WHEN A.TRIGGER_NAME IS NULL THEN 'other_schema'"
            " WHEN B.TRIGGER_NAME IS NULL THEN 'schema' ELSE 'both' END AS ONLY_IN,"
            " COALESCE(A.SUBJECT_TABLE_NAME, B.SUBJECT_TABLE_NAME) AS TABLE_NAME,"
            " COALESCE(A.TRIGGER_NAME, B.TRIGGER_NAME) AS TRIGGER_NAME,"
            " A.TRIGGER_ACTION_TIME AS TRIGGER_ACTION_TIME,"
            " B.TRIGGER_ACTION_TIME AS OTHER_TRIGGER_ACTION_TIME,"
            " A.TRIGGER_EVENT AS TRIGGER_EVENT, B.TRIGGER_EVENT AS OTHER_TRIGGER_EVENT"
            " FROM (SELECT SUBJECT_TABLE_NAME, TRIGGER_NAME, TRIGGER_ACTION_TIME, TRIGGER_EVENT"
            f" FROM SYS.TRIGGERS WHERE {_in_both('SUBJECT_TABLE_NAME')}) A"
            " FULL OUTER JOIN"
            " (SELECT SUBJECT_TABLE_NAME, TRIGGER_NAME, TRIGGER_ACTION_TIME, TRIGGER_EVENT"
            f" FROM SYS.TRIGGERS WHERE {_in_both('SUBJECT_TABLE_NAME')}) B"
            " ON A.SUBJECT_TABLE_NAME = B.SUBJECT_TABLE_NAME"
            " AND A.TRIGGER_NAME = B.TRIGGER_NAME"
            " WHERE A.TRIGGER_NAME IS NULL OR B.TRIGGER_NAME IS NULL"
            " OR A.TRIGGER_ACTION_TIME <> B.TRIGGER_ACTION_TIME"
            " OR A.TRIGGER_EVENT <> B.TRIGGER_EVENT"
            " ORDER BY TABLE_NAME, TRIGGER_NAME",
            _BOTH_BINDS,
        ),
    ),
    args=frozenset({"top", "schema", "other_schema"}),
    required=frozenset({"schema", "other_schema"}),
)

# on-prem: hana-cli reads TABLES, TABLE_COLUMNS per table and
# REFERENTIAL_CONSTRAINTS joined to KEY_COLUMNS (unqualified, string
# interpolated) and draws Mermaid / PlantUML / DBML. Here three parts with
# `?` binds, nothing drawn: `tables` (with their column count), `columns`
# (type, nullability, primary key flag from SYS.CONSTRAINTS) and `relations`
# (SYS.REFERENTIAL_CONSTRAINTS on-prem has one row per column, so the join to
# KEY_COLUMNS is not needed; the update and delete rules added). An optional
# `object` narrows all three to one table (its relations in either
# direction). The PostgreSQL branch is dropped.
# on-prem: not yet run
ERD_DIAGRAM = Check(
    name="erdDiagram",
    category="schema",
    purpose=("Tables, columns with key flag and foreign keys of a schema (optional table), as"
             " rows for a diagram the caller draws."),
    source="bin/erdDiagram.js",
    statements=(
        Statement(
            "tables",
            "SELECT TOP ? T.TABLE_NAME, T.TABLE_TYPE, COUNT(C.COLUMN_NAME) AS COLUMN_COUNT"
            " FROM SYS.TABLES T"
            " LEFT JOIN SYS.TABLE_COLUMNS C"
            " ON C.SCHEMA_NAME = T.SCHEMA_NAME AND C.TABLE_NAME = T.TABLE_NAME"
            f" WHERE T.SCHEMA_NAME = ? AND ({_NULL_OBJECT} OR T.TABLE_NAME = ?)"
            " GROUP BY T.TABLE_NAME, T.TABLE_TYPE"
            " ORDER BY T.TABLE_NAME",
            ("top_plus_one", "schema", "object", "object"),
        ),
        Statement(
            "columns",
            "SELECT TOP ? C.TABLE_NAME, C.COLUMN_NAME, C.POSITION, C.DATA_TYPE_NAME, C.LENGTH,"
            " C.SCALE, C.IS_NULLABLE,"
            " CASE WHEN K.COLUMN_NAME IS NULL THEN 'FALSE' ELSE 'TRUE' END AS IS_PRIMARY_KEY"
            " FROM SYS.TABLE_COLUMNS C"
            " LEFT JOIN (SELECT TABLE_NAME, COLUMN_NAME FROM SYS.CONSTRAINTS"
            " WHERE SCHEMA_NAME = ? AND IS_PRIMARY_KEY = 'TRUE') K"
            " ON K.TABLE_NAME = C.TABLE_NAME AND K.COLUMN_NAME = C.COLUMN_NAME"
            f" WHERE C.SCHEMA_NAME = ? AND ({_NULL_OBJECT} OR C.TABLE_NAME = ?)"
            " ORDER BY C.TABLE_NAME, C.POSITION",
            ("top_plus_one", "schema", "schema", "object", "object"),
        ),
        Statement(
            "relations",
            "SELECT TOP ? TABLE_NAME, COLUMN_NAME, POSITION, CONSTRAINT_NAME,"
            " REFERENCED_SCHEMA_NAME, REFERENCED_TABLE_NAME, REFERENCED_COLUMN_NAME,"
            " UPDATE_RULE, DELETE_RULE"
            " FROM SYS.REFERENTIAL_CONSTRAINTS"
            f" WHERE SCHEMA_NAME = ? AND ({_NULL_OBJECT} OR TABLE_NAME = ?"
            " OR REFERENCED_TABLE_NAME = ?)"
            " ORDER BY TABLE_NAME, CONSTRAINT_NAME, POSITION",
            ("top_plus_one", "schema", "object", "object", "object"),
        ),
    ),
    args=frozenset({"top", "schema", "object"}),
    required=frozenset({"schema"}),
)

# on-prem: hana-cli looks for OBJECT_TYPE 'GRAPHWORKSPACE' in SYS.OBJECTS
# and falls back on any table or view whose type holds GRAPH (HANA Cloud /
# HDI container views). On HANA 2.0 the catalogue view SYS.GRAPH_WORKSPACES
# names each workspace with its edge and vertex tables and key columns (the
# columns SAP lists as not available in HANA Cloud). The workspace-name
# filter is dropped; the schema filter is optional.
# on-prem: not yet run
GRAPH_WORKSPACES = Check(
    name="graphWorkspaces",
    category="schema",
    purpose="Graph workspaces with their edge and vertex tables and key columns; optional schema.",
    source="bin/graphWorkspaces.js",
    statements=(Statement(
        "",
        "SELECT TOP ? SCHEMA_NAME, WORKSPACE_NAME, EDGE_SCHEMA_NAME, EDGE_TABLE_NAME,"
        " EDGE_SOURCE_COLUMN_NAME, EDGE_TARGET_COLUMN_NAME, EDGE_KEY_COLUMN_NAME,"
        " VERTEX_SCHEMA_NAME, VERTEX_TABLE_NAME, VERTEX_KEY_COLUMN_NAME"
        " FROM SYS.GRAPH_WORKSPACES"
        " WHERE (CAST(? AS NVARCHAR(256)) IS NULL OR SCHEMA_NAME = ?)"
        " ORDER BY SCHEMA_NAME, WORKSPACE_NAME",
        ("top_plus_one", "schema", "schema"),
    ),),
    args=frozenset({"top", "schema"}),
)

CHECKS: tuple[Check, ...] = (COMPARE_SCHEMA, ERD_DIAGRAM, GRAPH_WORKSPACES)

register(*CHECKS)
