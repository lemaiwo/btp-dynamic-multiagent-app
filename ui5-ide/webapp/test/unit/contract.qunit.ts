QUnit.test("a broken response is reported with its path", function (assert) {
    const doc = schema;
    assert.deepEqual(validate(doc, "MeOut", { principal: "p", is_admin: false, targets: [], diagnose_targets: [] }),
        ["$.diagnose_retention_days: required, missing"], "a missing required field");
    const errors = validate(doc, "SessionDetailOut[]", [{ id: 1 }]);
    assert.ok(errors.includes("$[0].id: expected string, got number"), "a wrong type deep in a list");
    assert.ok(errors.some((e) => e.startsWith("$[0].title: required")), "and the missing fields");
    assert.ok(validate(doc, "FindingOut", { id: "f", kind: "nope" }).some((e) => e.startsWith("$.kind: \"nope\" is not one of")),
        "an enum value outside the contract");
});

QUnit.test("a keyword the validator does not implement throws instead of passing", function (assert) {
    const doc = (defs: Record<string, Record<string, unknown>>): SchemaDoc => ({ $defs: defs });
    assert.throws(() => validate(doc({ A: { allOf: [{ type: "string" }] } }), "A", "x"), /unsupported keyword allOf at \$/);
    assert.throws(() => validate(doc({ A: { type: "object", properties: { n: { type: "integer", maximum: 3 } } } }), "A", { n: 9 }),
        /unsupported keyword maximum at \$\.n/);
    assert.throws(() => validate(doc({ A: { type: "array", items: [{ type: "string" }] } }), "A", ["x"]),
        /unsupported keyword items \(tuple form\) at \$/);
    assert.throws(() => assertSupported(doc({ A: { type: "object", properties: { at: { type: "string", format: "date-time" } } } })),
        /unsupported keyword format at #\/\$defs\/A\/properties\/at/);
    assert.throws(() => assertSupported(doc({ A: { anyOf: [{ type: "array", minItems: 1 }] } })),
        /unsupported keyword minItems at #\/\$defs\/A\/anyOf\/0/);
    assert.deepEqual(validate(doc({ A: { title: "A", description: "d", default: 1, examples: [1], type: "integer" } }), "A", 1), [],
        "annotations pass");
});
