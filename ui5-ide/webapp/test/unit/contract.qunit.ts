/** Runs `body` against a fresh fake with a change and a diagnose session; answers the judged calls. */
async function probe(body: (fake: FakeBackend, svc: IdeService, sid: string) => Promise<void>): Promise<{ ex: Exchange; verdict: Verdict }[]> {
    const fake = new FakeBackend();
    fake.reset();
    const svc = new IdeService();
    let setup = 0;
    const list = await observed(fake, async (recorded) => {
        const session = await svc.createSession("Probe", "dev-system");
        setup = recorded.length;
        await body(fake, svc, session.id);
    });
    return judge(list.slice(setup));
}

QUnit.test("a fake answer without a required field fails, with its path", async function (assert) {
    const [call] = await probe(async (fake, svc) => {
        fake.failNext = { path: "me", status: 200, body: { is_admin: false, targets: [], diagnose_targets: [], diagnose_retention_days: 14 } };
        await svc.getMe();
    });
    assert.deepEqual(call.verdict.errors, ["$.principal: required, missing"]);
});

QUnit.test("an unknown field where additionalProperties is false fails", async function (assert) {
    const [call] = await probe(async (_fake, _svc, sid) => {
        await fetch(`backend/sessions/${sid}`, { method: "PATCH", body: JSON.stringify({ title: "x", colour: "red" }) });
    });
    assert.deepEqual(call.verdict.errors, ["request $.colour: not allowed"]);
});

QUnit.test("a wrong request body fails", async function (assert) {
    const calls = await probe(async (_fake, _svc, sid) => {
        await fetch(`backend/sessions/${sid}/messages`, { method: "POST", body: JSON.stringify({ message: "hi" }) });
        await fetch(`backend/sessions/${sid}/approve`, { method: "POST", body: JSON.stringify({ version: "1" }) });
        await fetch(`backend/sessions/${sid}/report`, { method: "POST", body: JSON.stringify({ text: "x" }) });
    });
    assert.ok(calls[0].verdict.errors.includes("request $.text: required, missing"), calls[0].verdict.errors.join("; "));
    assert.ok(calls[0].verdict.errors.includes("request $.message: not allowed"), "and the unknown field");
    assert.ok(calls[1].verdict.errors.some((e) => e.startsWith("request $.version: matches no anyOf branch")),
        calls[1].verdict.errors.join("; "));
    assert.ok(calls[2].verdict.errors.includes("request: a body where the route takes none"), calls[2].verdict.errors.join("; "));
});

QUnit.test("a call the fake does not serve fails", async function (assert) {
    const [call] = await probe(async () => {
        await fetch("backend/objects/search?q=Z", { method: "GET" });
    });
    assert.equal(call.ex.status, 404, "the dispatcher answers only its route table");
    assert.deepEqual(call.verdict.errors, ["GET objects/search: no x-routes entry (no fake route)"]);
});

